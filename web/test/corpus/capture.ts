/**
 * Regenerates the expected outputs in `j-corpus.tsv` from a real J console.
 *
 * Usage: node test/corpus/capture.ts <path-to-jconsole> [corpus-file]
 *
 * J is not needed to run the test suites; its outputs are checked in so CI
 * never depends on an installation. Each sentence is executed inside an
 * explicit verb with try/catch, so a failing sentence is captured as its
 * error class instead of aborting the script.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  parseCorpus,
  serializeCorpus,
  type CorpusCase,
} from './format.ts';

const [jconsole, corpusArgument] = process.argv.slice(2);
if (jconsole === undefined) {
  console.error('usage: node test/corpus/capture.ts <path-to-jconsole> [corpus-file]');
  process.exit(2);
}

const corpusPath =
  corpusArgument ?? fileURLToPath(new URL('./j-corpus.tsv', import.meta.url));
const cases = parseCorpus(readFileSync(corpusPath, 'utf8'));

const version = execFileSync(jconsole, ['-js', "smoutput 9!:14''"], {
  encoding: 'utf8',
  timeout: 30_000,
})
  .split(/\r?\n/)[0]
  .trim();

function jLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

const script: string[] = [
  'NB. Generated by web/test/corpus/capture.ts.',
  'NB. Five significant digits, matching the documented display of the port.',
  '9!:11 ] 5',
  'capture =: 3 : 0',
  '  try.',
  '    smoutput (". y)',
  '  catch.',
  "    smoutput '|',13!:12''",
  '  end.',
  ')',
];

for (const item of cases) {
  if (item.source.includes('\n')) {
    throw new Error(`multiline corpus sources are not supported: ${item.id}`);
  }
  script.push(`smoutput '<<<CASE>>> ${item.id}'`);
  script.push(`capture ${jLiteral(item.source)}`);
  script.push("smoutput '<<<END>>>'");
}
script.push('exit 0');

const directory = mkdtempSync(join(tmpdir(), 'j-corpus-'));
const scriptPath = join(directory, 'capture.ijs');
writeFileSync(scriptPath, `${script.join('\n')}\n`, 'utf8');

const output = execFileSync(jconsole, [scriptPath], {
  encoding: 'utf8',
  timeout: 120_000,
  stdio: ['ignore', 'pipe', 'pipe'],
});

/** J's diagnostics span several lines; the suites compare the error class. */
function normalizeError(lines: readonly string[]): string {
  for (const line of lines) {
    const match = line.match(/\|+\s*([a-z]+ error)/);
    if (match !== null) {
      return `|${match[1]}`;
    }
  }
  return lines[0] ?? '';
}

const captured = new Map<string, string>();
let current: string | null = null;
let block: string[] = [];

function finishBlock(): void {
  if (current === null) {
    return;
  }
  if (block.length > 0 && block[block.length - 1] === '') {
    block.pop();
  }
  const text = block.join('\n');
  captured.set(current, text.startsWith('|') ? normalizeError(block) : text);
  current = null;
  block = [];
}

for (const line of output.split(/\r?\n/)) {
  if (line.startsWith('<<<CASE>>> ')) {
    finishBlock();
    current = line.slice('<<<CASE>>> '.length);
    block = [];
  } else if (line === '<<<END>>>') {
    finishBlock();
  } else if (current !== null) {
    block.push(line);
  }
}
finishBlock();

const missing = cases.filter((item) => !captured.has(item.id));
if (missing.length > 0) {
  throw new Error(`J produced no output for: ${missing.map((item) => item.id).join(', ')}`);
}

const updated: CorpusCase[] = cases.map((item) => ({
  ...item,
  expected: captured.get(item.id) ?? '',
}));

const header = [
  `J corpus captured from real J: ${version}`,
  'Settings: 9!:11 ] 5 (five significant digits, matching the documented display).',
  'Regenerate with: node test/corpus/capture.ts <path-to-jconsole>',
  'Columns: id <TAB> source <TAB> expected.',
  'Escapes: \\\\ backslash, \\n newline, \\t tab. Everything else is literal.',
  "J's multi-line error diagnostics are reduced to the error class, e.g. |length error.",
];

writeFileSync(corpusPath, serializeCorpus(updated, header), 'utf8');
console.log(`wrote ${updated.length} cases to ${corpusPath} from ${version}`);
